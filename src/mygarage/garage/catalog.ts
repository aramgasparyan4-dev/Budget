/** patterns on the model name for makes or models not in the table */
const PATTERNS: [RegExp, ArchetypeId][] = [
  [/\b(pick-?up|hilux|navara|l200|triton|ranger|tacoma|tundra|f-?150|silverado|amarok|d-?max|gladiator|ram\b)/i, 'utility'],
  [/\b(van|sprinter|transit|vito|starex|staria|h-?1\b|caravelle|transporter|gazel|ducato|master|boxer|crafter|hiace|delica|minivan|mpv)/i, 'utility'],
  [/\b(land ?cruiser|prado|patrol|pajero|niva|uaz|g-?class|wrangler|defender|4runner|discovery|hunter|jimny|tahoe|escalade|4x4)\b/i, 'offroad'],
  [/\b(gti|type ?r|\bst\b|\brs\s?\d?|\bn\b|wrx|sti|cupra|abarth|evo(lution)?)\b/i, 'hatch'],
  [/\b(gt|coupe|coupé|roadster|spyder|spider|cabrio|convertible|amg gt|turbo s)\b/i, 'sports'],
  [/\b(ev|e-tron|electric|eq[a-z]|id\.\d|ioniq|leaf|model [3syx]|bz\d)\b/i, 'ev'],
  [/\b(suv|crossover|cross|x-?trail|cr-?v|rav ?4|tiggo|tucson|sportage|qashqai|x[1-6]\b|q[2-8]\b|gl[abce]\b|dx\d)/i, 'crossover'],
];

export interface MatchResult {
  archetype: ArchetypeId;
  /** how the match was made, for the "why this type" note */
  how: 'electric' | 'model' | 'pattern' | 'make' | 'age' | 'default';
}

const norm = (s: string) => s.trim().toLowerCase().replace(/\s+/g, ' ');

export function makeKey(make: string): string {
  const m = norm(make);
  return MAKE_ALIASES[m] ?? m;
}

/** the archetype a car drives as */
export function matchArchetype(make: string, model: string, year?: number, engine?: string): MatchResult {
  if (engine && /electric|ev\b|электро/i.test(engine)) return { archetype: 'ev', how: 'electric' };
  const mk = MAKES[makeKey(make)];
  const md = norm(model);
  if (mk) {
    if (mk.models[md]) return { archetype: mk.models[md], how: 'model' };
    // "Camry XV70", "Land Cruiser 200", "E 220": try the longest known model name the text starts with
    const keys = Object.keys(mk.models).sort((a, b) => b.length - a.length);
    const k = keys.find((x) => md.startsWith(x + ' ') || md.startsWith(x + '-') || md === x);
    if (k) return { archetype: mk.models[k], how: 'model' };
  }
  for (const [re, a] of PATTERNS) if (re.test(md)) return { archetype: a, how: 'pattern' };
  if (year !== undefined && year < 1990) return { archetype: 'classic', how: 'age' };
  if (mk) return { archetype: mk.usual, how: 'make' };
  return { archetype: 'sedan', how: 'default' };
}

/** makes for the manual "add a vehicle" form, A-Z */
export function knownMakes(): { key: string; name: string }[] {
  return Object.entries(MAKES)
    .filter(([k]) => k !== 'vaz')
    .map(([key, v]) => ({ key, name: v.name }))
    .sort((a, b) => a.name.localeCompare(b.name));
}

/** models we know for a make (display names, title-cased) */
export function knownModels(make: string): string[] {
  const mk = MAKES[makeKey(make)];
  if (!mk) return [];
  return Object.keys(mk.models).map((m) => (/^[a-z]/.test(m) && m.length > 3 ? m.replace(/\b\w/g, (c) => c.toUpperCase()) : m.toUpperCase()));
}

/** display name for a make key or free text */
export function makeName(make: string): string {
  return MAKES[makeKey(make)]?.name ?? make.trim();
}
